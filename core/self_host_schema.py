@dataclass(frozen=True)
class TableSpec:
    name: str
    columns: tuple[Column, ...]
    access: str
    constraints: tuple[str, ...] = ()
    indexes: tuple[str, ...] = ()
    comment: str = ""


def _versioned(columns: tuple[tuple[str, str, str], ...]) -> tuple[Column, ...]:
    """把 core/*_schema.py 里 (列名, 类型, 注释) 的补列常量转成本模块的列。"""
    return tuple((name, spec) for name, spec, _note in columns)


def _candidate_attribution_columns() -> tuple[Column, ...]:
    jsonb_columns = {"candidate_reasons", "candidate_metrics", "dynamic_shadow_promotion"}
    numeric_columns = {
        "mainline_score",
        "theme_score",
        "stock_role_score",
        "quality_score",
        "timing_score",
        "dynamic_shadow_score",
    }

    def spec(name: str) -> str:
        if name in jsonb_columns:
            return "jsonb"
        return "numeric" if name in numeric_columns else "text"

    return tuple((name, spec(name)) for name in CANDIDATE_ATTRIBUTION_COLUMNS)


