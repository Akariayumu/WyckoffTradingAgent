"""自部署用的完整 Supabase schema：建齐全部云端表、唯一约束与 RLS。

上游只版本化了少数表（factor_ic / review_* / shadow_ledger 的完整 DDL，以及
recommendation_tracking / signal_policy_shadow_runs / daily_nav 的补列），其余表
只存在于作者的生产库里。这里按写入与读取代码反推字段，给新建的 Supabase 项目
一次性建库用。与 core/*_schema.py 同一套做法：不提交 .sql，由
``scripts/print_self_host_ddl.py`` 打印后在 SQL Editor 执行。

约定：
- 已有模块版本化的列/表直接引用，不在这里重抄，上游改 schema 时自动跟上。
- 日期列一律 ``date``（写入侧都是 YYYY-MM-DD）；``recommend_date`` 是 YYYYMMDD 整数。
- 结构化或列表字段用 ``jsonb``——写入侧传 dict / list，读取侧按 JSON 解析。
- 每个 upsert 的 on_conflict 键都必须有同列的唯一约束，否则 PostgREST 报 42P10。
- 共享表只开放 authenticated 读；写入走 service_role（绕过 RLS），与
  ``WYCKOFF_WRITE_CONTEXT=server_job`` 的写库边界一致。
"""

