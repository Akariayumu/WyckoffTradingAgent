def _dedupe(columns: tuple[Column, ...]) -> tuple[Column, ...]:
    """按列名去重，保留首次出现的定义（补列常量可能与反推的列重叠）。"""
    seen: set[str] = set()
    out = []
    for name, spec in columns:
        if name not in seen:
            seen.add(name)
            out.append((name, spec))
    return tuple(out)


def _tracking_table(name: str, code_type: str, extra: tuple[Column, ...] = ()) -> TableSpec:
    return TableSpec(
        name=name,
        columns=_dedupe(
            (_ID, ("code", f"{code_type} not null"), *_TRACKING_BASE_COLUMNS, *extra, *_PERFORMANCE_COLUMNS)
            + (_CREATED_AT, _UPDATED_AT)
        ),
        access=SHARED_READ,
        constraints=(f"constraint {name}_code_date_key unique (code, recommend_date)",),
        indexes=(f"create index if not exists {name}_date_idx on public.{name} (recommend_date desc, code)",),
    )


