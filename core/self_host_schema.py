# 建表语句由已有模块提供的表（本模块只负责 RLS 与策略）。
VERSIONED_TABLES: tuple[tuple[str, str], ...] = (
    (TABLE_FACTOR_IC_DAILY, SHARED_READ),
    (TABLE_REVIEW_CAPTURE_DAILY, SHARED_READ),
    (TABLE_REVIEW_SHADOW_LANE_DAILY, SHARED_READ),
    *((name, SERVICE_ONLY) for name in shadow_ledger_schema.table_names()),
)

_UID = "(select auth.uid())::text"
_PORTFOLIO_OWNER = f"split_part(portfolio_id, ':', 2) = {_UID}"


def table_access() -> dict[str, str]:
    """全部表名 → 访问模式。"""
    return {**{spec.name: spec.access for spec in TABLES}, **dict(VERSIONED_TABLES)}


def _create_table(spec: TableSpec) -> str:
    parts = [f"  {name} {ddl}" for name, ddl in spec.columns] + [f"  {c}" for c in spec.constraints]
    lines = [f"create table if not exists public.{spec.name} (", ",\n".join(parts), ");"]
    lines.extend(f"{index};" for index in spec.indexes)
    if spec.comment:
        comment = spec.comment.replace("'", "''")
        lines.append(f"comment on table public.{spec.name} is '{comment}';")
    return "\n".join(lines)


def _policy(table: str, suffix: str, command: str, *, using: str | None = None, check: str | None = None) -> str:
    name = f"{table}_{suffix}"
    clauses = [f"create policy {name} on public.{table} for {command} to authenticated"]
    if using:
        clauses.append(f"  using ({using})")
    if check:
        clauses.append(f"  with check ({check})")
    return f"drop policy if exists {name} on public.{table};\n" + "\n".join(clauses) + ";"


def _policy_statements(table: str, access: str) -> list[str]:
    own = f"user_id = {_UID}"
    if access == OWN_USER_READ:
        return [_policy(table, "select_own", "select", using=own)]
    if access == OWN_USER_ALL:
        return [_policy(table, "all_own", "all", using=own, check=own)]
    if access == ACTIVITY_EVENTS:
        return [
            _policy(table, "select_own", "select", using=own),
            _policy(table, "insert_own", "insert", check=own),
        ]
    if access == ACTIVITY_DAILY:
        return [
            _policy(table, "select_own", "select", using=own),
            _policy(table, "insert_own", "insert", check=own),
            _policy(table, "update_own", "update", using=own, check=own),
        ]
    if access == PORTFOLIO_ALL:
        return [_policy(table, "all_own", "all", using=_PORTFOLIO_OWNER, check=_PORTFOLIO_OWNER)]
    if access == PORTFOLIO_READ:
        return [_policy(table, "select_own", "select", using=_PORTFOLIO_OWNER)]
    if access == SHARED_READ:
        return [_policy(table, "select_authenticated", "select", using="true")]
    if access == SERVICE_ONLY:
        return []
    raise ValueError(f"unknown access mode {access!r} for {table}")


def _rls_block(access_map: dict[str, str]) -> str:
    lines = [
        "-- RLS：未列出的角色与操作一律拒绝；service_role 绕过 RLS，供定时任务写库。",
    ]
    for table, access in access_map.items():
        lines.append(f"alter table public.{table} enable row level security;")
        lines.append(f"revoke all on table public.{table} from anon;")
        lines.extend(_policy_statements(table, access))
    return "\n".join(lines)


def build_ddl() -> str:
    """生成完整、幂等的建库脚本。

    重复执行只会补建缺失的表、索引与策略；已存在的表不会补列，上游新增列时要另写
    ``alter table ... add column if not exists``（参照 core/*_schema.py 的补列模块）。
    """
    blocks = [
        "-- WyckoffTradingAgent 自部署完整 schema。由 core/self_host_schema.py 生成，请勿手改。",
        "-- 在 Supabase SQL Editor 中整段执行；脚本幂等，可重复执行。",
        "begin;",
        *(_create_table(spec) for spec in TABLES),
        "-- 以下建表语句来自已有的 schema 模块。",
        factor_ic_schema.build_ddl(),
        review_capture_schema.build_ddl(),
        review_shadow_lane_schema.build_ddl(),
        shadow_ledger_schema.build_ddl(),
        _rls_block(table_access()),
        "notify pgrst, 'reload schema';",
        "commit;",
    ]
    return "\n\n".join(block.strip() for block in blocks) + "\n"
